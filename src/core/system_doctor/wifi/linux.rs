//! NetworkManager adapter. Only fresh, explicitly open infrastructure APs are
//! eligible; activation always uses a new, nonpersistent, non-autoconnect profile.
//! See <https://networkmanager.dev/docs/api/latest/nmcli.html>.

use std::{collections::BTreeMap, process::Stdio, sync::Arc, time::Duration};

use async_trait::async_trait;
use tokio::{
    io::{AsyncRead, AsyncReadExt},
    process::Command,
    sync::Mutex,
    time::timeout,
};

use super::{OpenNetwork, WifiAdapter, WifiError};

const WIFI_FIELDS: &str = "SSID,SSID-HEX,BSSID,SECURITY,SIGNAL,MODE,WPA-FLAGS,RSN-FLAGS";
const COMMAND_TIMEOUT: Duration = Duration::from_secs(35);
const MAX_OUTPUT_BYTES: u64 = 256 * 1024;

pub struct LinuxWifi {
    configured_interface: Option<String>,
    state: Mutex<AdapterState>,
    runner: Arc<dyn NmcliRunner>,
}

#[derive(Default)]
struct AdapterState {
    interface: Option<String>,
    /// Only UUIDs generated by this adapter are ever deleted.
    attempt_uuid: Option<String>,
    /// Keep the original saved connection across multiple fallback episodes.
    original_uuid: Option<String>,
    baseline_known: bool,
}

struct CommandOutput {
    code: i32,
    stdout: String,
    stderr: String,
}

impl CommandOutput {
    fn checked(self) -> Result<String, WifiError> {
        if self.code == 0 {
            return Ok(self.stdout);
        }
        // NetworkManager does not reserve a distinct exit code for PolicyKit
        // failures. Retain a typed error without retaining/logging raw output.
        let message = format!("{} {}", self.stdout, self.stderr).to_ascii_lowercase();
        if [
            "not authorized",
            "not authorised",
            "permission denied",
            "insufficient privileges",
            "not permitted",
            "authorization failed",
        ]
        .iter()
        .any(|part| message.contains(part))
        {
            return Err(WifiError::PermissionDenied);
        }
        Err(match self.code {
            2 => WifiError::InvalidConfiguration,
            3 => WifiError::TimedOut,
            8 | 10 => WifiError::Unavailable,
            _ => WifiError::CommandFailed,
        })
    }
}

#[async_trait]
trait NmcliRunner: Send + Sync {
    async fn run(&self, args: &[&str]) -> Result<CommandOutput, WifiError>;
}

struct SystemNmcli;

#[async_trait]
impl NmcliRunner for SystemNmcli {
    async fn run(&self, args: &[&str]) -> Result<CommandOutput, WifiError> {
        let mut child = Command::new("nmcli")
            .args([
                "--terse", "--escape", "yes", "--colors", "no", "--wait", "25",
            ])
            .args(args)
            .env("LC_ALL", "C")
            .env("LANG", "C")
            .env("TERM", "dumb")
            .env("PAGER", "")
            .env("NO_COLOR", "1")
            .env_remove("CLICOLOR_FORCE")
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .kill_on_drop(true)
            .spawn()
            .map_err(io_error)?;
        let stdout = child.stdout.take().ok_or(WifiError::CommandFailed)?;
        let stderr = child.stderr.take().ok_or(WifiError::CommandFailed)?;
        let result = timeout(COMMAND_TIMEOUT, async {
            let (stdout, stderr, status) =
                tokio::try_join!(read_bounded(stdout), read_bounded(stderr), async {
                    child.wait().await.map_err(io_error)
                },)?;
            Ok(CommandOutput {
                code: status.code().unwrap_or(-1),
                stdout: String::from_utf8(stdout).map_err(|_| WifiError::InvalidOutput)?,
                stderr: String::from_utf8(stderr).map_err(|_| WifiError::InvalidOutput)?,
            })
        })
        .await;
        match result {
            Ok(Ok(output)) => Ok(output),
            result => {
                // Cancel our own client on timeout/oversized output. Deleting
                // the owned profile separately cancels an in-flight activation.
                let _ = child.kill().await;
                let _ = child.wait().await;
                Err(match result {
                    Ok(Err(error)) => error,
                    Err(_) => WifiError::TimedOut,
                    Ok(Ok(_)) => unreachable!(),
                })
            }
        }
    }
}

fn io_error(error: std::io::Error) -> WifiError {
    match error.kind() {
        std::io::ErrorKind::NotFound => WifiError::Unavailable,
        std::io::ErrorKind::PermissionDenied => WifiError::PermissionDenied,
        _ => WifiError::CommandFailed,
    }
}

async fn read_bounded(reader: impl AsyncRead + Unpin) -> Result<Vec<u8>, WifiError> {
    let mut bytes = Vec::new();
    reader
        .take(MAX_OUTPUT_BYTES + 1)
        .read_to_end(&mut bytes)
        .await
        .map_err(io_error)?;
    if bytes.len() as u64 > MAX_OUTPUT_BYTES {
        return Err(WifiError::InvalidOutput);
    }
    Ok(bytes)
}

impl LinuxWifi {
    pub fn new(interface: Option<String>) -> Self {
        Self {
            configured_interface: interface,
            state: Mutex::new(AdapterState::default()),
            runner: Arc::new(SystemNmcli),
        }
    }

    async fn run(&self, args: &[&str]) -> Result<String, WifiError> {
        self.runner.run(args).await?.checked()
    }

    async fn interface(&self, state: &mut AdapterState) -> Result<String, WifiError> {
        let configured = self
            .configured_interface
            .as_deref()
            .or(state.interface.as_deref());
        if configured.is_some_and(|name| !valid_interface(name)) {
            return Err(WifiError::InvalidConfiguration);
        }
        // Recheck the device type before every operation; a configured Ethernet
        // interface or a disappeared/replaced Wi-Fi device must never be used.
        let output = self
            .run(&["--fields", "DEVICE,TYPE,STATE", "device", "status"])
            .await?;
        let selected = select_interface(&output, configured)?;
        state.interface = Some(selected.clone());
        Ok(selected)
    }

    async fn scan(&self, interface: &str) -> Result<Vec<OpenNetwork>, WifiError> {
        let output = self
            .run(&[
                "--fields",
                WIFI_FIELDS,
                "device",
                "wifi",
                "list",
                "ifname",
                interface,
                "--rescan",
                "yes",
            ])
            .await?;
        parse_open_networks(&output)
    }

    async fn remember_connection(
        &self,
        state: &mut AdapterState,
        interface: &str,
    ) -> Result<Option<String>, WifiError> {
        let output = self
            .run(&[
                "--get-values",
                "GENERAL.CON-UUID",
                "device",
                "show",
                interface,
            ])
            .await?;
        let current = match output.trim() {
            "" | "--" => None,
            uuid if valid_uuid(uuid) => Some(uuid.to_owned()),
            _ => return Err(WifiError::InvalidOutput),
        };
        if state.attempt_uuid.is_some() && state.attempt_uuid == current {
            return Ok(state.original_uuid.clone());
        }
        // Between failed candidates the owned profile has been removed and the
        // device can be disconnected. That must not erase the original UUID.
        if !state.baseline_known || current.is_some() {
            state.original_uuid = current.clone();
            state.baseline_known = true;
        }
        Ok(state.original_uuid.clone())
    }

    async fn delete_attempt(&self, state: &mut AdapterState) -> Result<(), WifiError> {
        if let Some(uuid) = state.attempt_uuid.as_deref() {
            let output = self
                .runner
                .run(&["connection", "delete", "uuid", uuid])
                .await?;
            // Exit 10 means the exact profile is already absent (for example,
            // removed by an operator). Never broaden cleanup to names/devices.
            if output.code != 10 {
                output.checked()?;
            }
            state.attempt_uuid = None;
        }
        Ok(())
    }
}

#[async_trait]
impl WifiAdapter for LinuxWifi {
    async fn current_connection(&self) -> Result<Option<String>, WifiError> {
        let mut state = self.state.lock().await;
        let interface = self.interface(&mut state).await?;
        self.remember_connection(&mut state, &interface).await
    }

    async fn scan_open(&self) -> Result<Vec<OpenNetwork>, WifiError> {
        let mut state = self.state.lock().await;
        let interface = self.interface(&mut state).await?;
        self.scan(&interface).await
    }

    async fn connect_open(&self, network: &OpenNetwork) -> Result<(), WifiError> {
        if !valid_ssid(&network.ssid) || !valid_bssid(&network.bssid) {
            return Err(WifiError::InvalidConfiguration);
        }
        let mut state = self.state.lock().await;
        let interface = self.interface(&mut state).await?;
        self.remember_connection(&mut state, &interface).await?;
        self.delete_attempt(&mut state).await?;
        // Do not trust a previously returned scan or a caller-supplied SSID.
        // Revalidate the exact BSSID and SSID before creating an open profile.
        let fresh = self.scan(&interface).await?;
        if !fresh.iter().any(|candidate| {
            candidate.bssid.eq_ignore_ascii_case(&network.bssid) && candidate.ssid == network.ssid
        }) {
            return Err(WifiError::Unavailable);
        }

        let uuid = new_uuid();
        let name = format!("mini-erp-doctor-{uuid}");
        // Track before add: if nmcli times out after NM creates the profile,
        // cleanup can still address precisely this UUID.
        state.attempt_uuid = Some(uuid.clone());
        let result = async {
            self.run(&[
                "connection",
                "add",
                "save",
                "no",
                "type",
                "wifi",
                "ifname",
                &interface,
                "con-name",
                &name,
                "connection.uuid",
                &uuid,
                "connection.autoconnect",
                "no",
                "802-11-wireless.mode",
                "infrastructure",
                "802-11-wireless.ssid",
                &network.ssid,
                "802-11-wireless.bssid",
                &network.bssid,
                "ipv4.method",
                "auto",
                "ipv6.method",
                "auto",
            ])
            .await?;
            // No security setting exists in this new profile. A protected AP
            // cannot reuse saved credentials or a matching saved SSID profile.
            self.run(&[
                "connection",
                "up",
                "uuid",
                &uuid,
                "ifname",
                &interface,
                "ap",
                &network.bssid,
            ])
            .await?;
            Ok(())
        }
        .await;
        if result.is_err() {
            // Keep ownership for retry if cleanup itself is unavailable/denied.
            let _ = self.delete_attempt(&mut state).await;
        }
        result
    }

    async fn disconnect_attempt(&self) -> Result<(), WifiError> {
        let mut state = self.state.lock().await;
        self.delete_attempt(&mut state).await
    }

    async fn restore_connection(&self, previous: &str) -> Result<(), WifiError> {
        if !valid_uuid(previous) {
            return Err(WifiError::InvalidConfiguration);
        }
        let mut state = self.state.lock().await;
        // Do not delete a profile we are being asked to restore.
        if state.attempt_uuid.as_deref() == Some(previous) {
            return Err(WifiError::InvalidConfiguration);
        }
        let interface = self.interface(&mut state).await?;
        let connection_type = self
            .run(&[
                "--get-values",
                "connection.type",
                "connection",
                "show",
                "uuid",
                previous,
            ])
            .await?;
        if connection_type.trim() != "802-11-wireless" {
            return Err(WifiError::InvalidConfiguration);
        }
        self.delete_attempt(&mut state).await?;
        self.run(&["connection", "up", "uuid", previous, "ifname", &interface])
            .await?;
        Ok(())
    }
}

fn valid_interface(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 15
        && value != "."
        && value != ".."
        && !value.starts_with('-')
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || b"_.-".contains(&byte))
}

fn valid_ssid(value: &str) -> bool {
    !value.is_empty() && value.len() <= 32 && !value.chars().any(char::is_control)
}

fn valid_bssid(value: &str) -> bool {
    let bytes = value.as_bytes();
    if bytes.len() != 17
        || !bytes.iter().enumerate().all(|(index, byte)| {
            if index % 3 == 2 {
                *byte == b':'
            } else {
                byte.is_ascii_hexdigit()
            }
        })
    {
        return false;
    }
    let first = u8::from_str_radix(&value[..2], 16).unwrap_or(1);
    first & 1 == 0 && value != "00:00:00:00:00:00"
}

fn valid_uuid(value: &str) -> bool {
    value.len() == 36
        && value.bytes().enumerate().all(|(index, byte)| {
            if [8, 13, 18, 23].contains(&index) {
                byte == b'-'
            } else {
                byte.is_ascii_hexdigit()
            }
        })
}

fn new_uuid() -> String {
    let mut bytes = rand::random::<[u8; 16]>();
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    let hex: String = bytes.iter().map(|byte| format!("{byte:02x}")).collect();
    format!(
        "{}-{}-{}-{}-{}",
        &hex[..8],
        &hex[8..12],
        &hex[12..16],
        &hex[16..20],
        &hex[20..]
    )
}

/// nmcli's terse mode escapes only `:` and `\\`, not arbitrary C sequences.
fn fields(line: &str) -> Result<Vec<String>, WifiError> {
    let mut fields = vec![String::new()];
    let mut escaped = false;
    for character in line.chars() {
        if escaped {
            if !matches!(character, ':' | '\\') {
                return Err(WifiError::InvalidOutput);
            }
            fields.last_mut().unwrap().push(character);
            escaped = false;
        } else {
            match character {
                '\\' => escaped = true,
                ':' => fields.push(String::new()),
                _ => fields.last_mut().unwrap().push(character),
            }
        }
    }
    if escaped {
        return Err(WifiError::InvalidOutput);
    }
    Ok(fields)
}

fn select_interface(output: &str, configured: Option<&str>) -> Result<String, WifiError> {
    let mut candidates = Vec::new();
    for line in output.lines().filter(|line| !line.is_empty()) {
        let row = fields(line)?;
        if row.len() != 3 {
            return Err(WifiError::InvalidOutput);
        }
        if configured.is_some_and(|name| name == row[0]) && row[1] != "wifi" {
            return Err(WifiError::InvalidConfiguration);
        }
        if row[1] != "wifi"
            || !valid_interface(&row[0])
            || matches!(row[2].as_str(), "unavailable" | "unmanaged" | "unknown")
            || configured.is_some_and(|name| name != row[0])
        {
            continue;
        }
        // Prefer an already connected Wi-Fi interface when auto-detecting.
        candidates.push((!row[2].starts_with("connected"), row[0].clone()));
    }
    candidates.sort();
    candidates
        .into_iter()
        .next()
        .map(|(_, name)| name)
        .ok_or(WifiError::Unavailable)
}

fn ssid_matches_hex(ssid: &str, hex: &str) -> bool {
    hex.len() == ssid.len() * 2
        && ssid
            .bytes()
            .zip(hex.as_bytes().chunks(2))
            .all(|(byte, hex)| {
                hex.len() == 2
                    && hex.iter().all(u8::is_ascii_hexdigit)
                    && std::str::from_utf8(hex)
                        .ok()
                        .and_then(|hex| u8::from_str_radix(hex, 16).ok())
                        == Some(byte)
            })
}

fn parse_open_networks(output: &str) -> Result<Vec<OpenNetwork>, WifiError> {
    let mut networks = BTreeMap::<String, Option<OpenNetwork>>::new();
    for line in output.lines().filter(|line| !line.is_empty()) {
        let row = fields(line)?;
        if row.len() != 8 {
            return Err(WifiError::InvalidOutput);
        }
        if !valid_bssid(&row[2]) {
            continue;
        }
        let bssid = row[2].to_ascii_uppercase();
        let signal = row[4].parse::<i32>().ok().filter(|v| (0..=100).contains(v));
        // SECURITY also catches WEP's privacy flag. WPA/RSN flags independently
        // reject OWE/unknown secured variants even if SECURITY is unrecognized.
        let open = valid_ssid(&row[0])
            && ssid_matches_hex(&row[0], &row[1])
            && matches!(row[3].as_str(), "" | "--")
            && row[5] == "Infra"
            && row[6] == "(none)"
            && row[7] == "(none)"
            && signal.is_some();
        if !open {
            // An ambiguous BSSID with any secured/malformed observation is not
            // eligible, regardless of the order of observations in this scan.
            networks.insert(bssid, None);
            continue;
        }
        let network = OpenNetwork {
            ssid: row[0].clone(),
            bssid: bssid.clone(),
            signal: signal.unwrap(),
        };
        match networks.entry(bssid) {
            std::collections::btree_map::Entry::Vacant(entry) => {
                entry.insert(Some(network));
            }
            std::collections::btree_map::Entry::Occupied(mut entry) => {
                if let Some(existing) = entry.get_mut() {
                    if existing.ssid != network.ssid {
                        entry.insert(None);
                    } else {
                        existing.signal = existing.signal.max(network.signal);
                    }
                }
            }
        }
    }
    let mut networks: Vec<_> = networks.into_values().flatten().collect();
    networks.sort_by(|a, b| b.signal.cmp(&a.signal).then(a.bssid.cmp(&b.bssid)));
    Ok(networks)
}

